function renderTeacherTimetable(el){
  const ids=Object.keys(REEDS_FIRST_YEAR_TIMETABLES.teachers);
  if(!ids.includes(state.teacherId)) state.teacherId=ids[0];
  const picker=document.createElement('div');
  picker.className='teacher-picker';
  const label=document.createElement('label');
  label.htmlFor='teacherTimetableSelect';
  label.textContent='選擇教師';
  const select=document.createElement('select');
  select.id='teacherTimetableSelect';
  REEDS_FIRST_YEAR_STAFFING.teachers.forEach(t=>{
    const option=document.createElement('option');
    option.value=t.code;
    option.textContent=`教師 ${t.code}｜${t.role}｜每週${REEDS_FIRST_YEAR_TIMETABLES.loads[t.code]}節`;
    select.appendChild(option);
  });
  select.value=state.teacherId;
  select.onchange=()=>{state.teacherId=select.value;renderContent();};
  picker.append(label,select);
  el.appendChild(picker);
  renderFixedTimetable(el,'teacher',state.teacherId);
}

function renderFixedTimetable(el,type,id){
  const p=REEDS_FIRST_YEAR_TIMETABLES;
  const isTeacher=type==='teacher';
  const rows=(isTeacher?p.teachers:p.classes)[id];
  const heading=document.createElement('h2');
  heading.textContent=isTeacher?`教師 ${id} 個人週課表`:`${id}班 班級週課表`;
  el.appendChild(heading);
  const sub=document.createElement('p');
  if(isTeacher){
    const teacher=REEDS_FIRST_YEAR_STAFFING.teachers.find(t=>t.code===id);
    sub.textContent=`${teacher.role}｜每週固定 ${p.loads[id]} 節｜各格列出授課班級、課程與語言`;
  }else{
    const cls=REEDS_FIRST_YEAR_STAFFING.classes.find(c=>c.id===id);
    sub.textContent=`${cls.name}｜中文導師 ${cls.chinese}、外籍導師 ${cls.english}｜每週35節`;
  }
  el.appendChild(sub);
  const wrap=document.createElement('div');
  wrap.className='fixed-timetable-wrap';
  const table=document.createElement('table');
  table.className='fixed-timetable';
  const caption=table.createCaption();
  caption.textContent='固定節數版｜週一至週五；週五全天陽明山，各班獨立授課';
  const header=table.createTHead().insertRow();
  ['節次／時間',...p.days].forEach(value=>{const th=document.createElement('th');th.scope='col';th.textContent=value;header.appendChild(th);});
  const body=table.createTBody();
  rows.forEach((row,index)=>{
    const tr=body.insertRow();
    const th=document.createElement('th');th.scope='row';th.textContent=p.periods[index];tr.appendChild(th);
    row.forEach(value=>{
      const td=tr.insertCell();td.textContent=value;
      td.className=value==='—'?'empty':value.includes('【中文】')?'lang-zh':value.includes('【英語】')?'lang-en':value.includes('【中英雙語】')?'lang-bi':'lang-local';
    });
  });
  wrap.appendChild(table);el.appendChild(wrap);
  const legend=document.createElement('div');legend.className='timetable-legend';
  ['中文','英語','中英雙語','選修語別','— 無排課'].forEach(text=>{const span=document.createElement('span');span.textContent=text;legend.appendChild(span);});
  el.appendChild(legend);
  const note=document.createElement('p');note.className='staff-note';
  note.textContent='午餐與午休12:00–13:00；交通與集合不計教學節次。空白時段不代表教師一定可被排入新課。行政、備課、午休照護、交通及戶外安全協同人力不計入授課節數；教師可到校時段與場地仍須確認。本土語文／臺灣手語暫列中文導師代碼，須依選修語別及授課資格確認。';
  el.appendChild(note);
  const source=document.createElement('p');source.className='hint';source.textContent=`資料來源：${p.source}｜${isTeacher?id+'教師課表':id+'班課表'}`;el.appendChild(source);
}
